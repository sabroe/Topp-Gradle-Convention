import org.gradle.api.plugins.JavaPlugin
import org.gradle.api.tasks.ClasspathNormalizer
import org.gradle.api.tasks.JavaExec
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.compile.JavaCompile
import org.gradle.api.tasks.javadoc.Javadoc
import org.gradle.kotlin.dsl.dependencies
import org.gradle.process.CommandLineArgumentProvider

plugins {
    id("java")  //Note: Required for type-safe dependency accessors!
}

val conventionName = "lombok"

project.logger.info("Convention ${conventionName} loaded.")

project.plugins.withType<JavaPlugin> {
    val enablePropertyName = "convention.${conventionName}.enable"
    val enable = project.findProperty(enablePropertyName)?.toString()?.trim()?.toBooleanStrictOrNull()?:true
    if (!enable) {
        project.logger.debug("Convention ${conventionName} disabled.")
    } else {
        project.logger.debug("Convention ${conventionName} enabled.")

        val lombokVersion = "1.18.48"
        val lombokDependency = "org.projectlombok:lombok:${lombokVersion}"

        dependencies {
            compileOnly(lombokDependency)
            annotationProcessor(lombokDependency)

            testCompileOnly(lombokDependency)
            testAnnotationProcessor(lombokDependency)
        }

        // Javadoc reads the delomboked main sources, so it shows everything Lombok generates.
        // Only the source of the 'javadoc' task is changed. Compilation and the sources jar use the original sources.
        // Javadoc options are left to other conventions, e.g. 'java-options'; each works without the other.
        val delombokEnablePropertyName = "convention.${conventionName}.delombok.enable"
        val delombokEnable = project.findProperty(delombokEnablePropertyName)?.toString()?.trim()?.toBooleanStrictOrNull()?:true
        if (!delombokEnable) {
            project.logger.debug("Convention ${conventionName}: delombok for Javadoc disabled.")
        } else {
            project.logger.debug("Convention ${conventionName}: delombok for Javadoc enabled.")

            val lombokTool = configurations.create("lombokTool") {
                description = "Lombok, run as a tool by the 'delombok' task."
                isCanBeConsumed = false
                isCanBeResolved = true
            }
            dependencies {
                add(lombokTool.name, lombokDependency)
            }

            val mainSourceSet = sourceSets.named("main")
            val delombokInputDir = layout.buildDirectory.dir("delombok/input/main")
            val delombokDir = layout.buildDirectory.dir("delombok/main")
            val compileEncoding = tasks.named<JavaCompile>("compileJava").map { it.options.encoding ?: "UTF-8" }

            // Delombok can't handle 'module-info.java'; it fails to set up the module path, and then Lombok
            // generates nothing. So the sources are delomboked without it, on the classpath, and
            // 'module-info.java' is copied unchanged into the result afterwards.
            val delombokInput = tasks.register<Sync>("delombokInput") {
                description = "Copies the main Java sources, except 'module-info.java', for the 'delombok' task."
                from(mainSourceSet.map { it.java.sourceDirectories })
                exclude("module-info.java")
                into(delombokInputDir)
            }

            val delombok = tasks.register<JavaExec>("delombok") {
                group = "documentation"
                description = "Writes the main Java sources with the code generated by Lombok, for Javadoc."

                val sourceDirs = mainSourceSet.get().java.sourceDirectories
                val compileClasspath = mainSourceSet.get().compileClasspath
                val inputDir = delombokInputDir
                val targetDir = delombokDir
                val encoding = compileEncoding

                dependsOn(delombokInput)
                inputs.dir(inputDir).withPathSensitivity(PathSensitivity.RELATIVE).withPropertyName("sources")
                inputs.files(sourceDirs.asFileTree.matching { include("module-info.java") })
                    .withPathSensitivity(PathSensitivity.RELATIVE).withPropertyName("moduleInfo")
                inputs.files(compileClasspath).withNormalizer(ClasspathNormalizer::class.java).withPropertyName("compileClasspath")
                inputs.property("encoding", encoding)
                outputs.dir(targetDir).withPropertyName("target")

                classpath = lombokTool
                mainClass.set("lombok.launch.Main")

                // Lombok uses 'sun.misc.Unsafe'. From JDK 24, the JVM then prints "WARNING: A terminally deprecated
                // method in sun.misc.Unsafe has been called" and three more lines, once per module. Compilation
                // doesn't show it; this task runs Lombok in a JVM of its own, so its output reaches the build log.
                // The option allows the use without the warning. JDK 23 introduced it, and older JDKs don't
                // start with an unknown option, so it is only added from JDK 23. A future JDK removes the methods;
                // then Lombok itself must change.
                val launcher = javaLauncher
                jvmArgumentProviders.add(CommandLineArgumentProvider {
                    if (launcher.get().metadata.languageVersion.canCompileOrRun(23)) {
                        listOf("--sun-misc-unsafe-memory-access=allow")
                    } else {
                        emptyList()
                    }
                })
                argumentProviders.add(CommandLineArgumentProvider {
                    listOf(
                        "delombok",
                        inputDir.get().asFile.absolutePath,
                        "--target=${targetDir.get().asFile.absolutePath}",
                        "--encoding=${encoding.get()}",
                        "--classpath=${compileClasspath.asPath}"
                    )
                })

                doFirst {
                    targetDir.get().asFile.deleteRecursively()  //Note: Removes files of deleted sources!
                }
                doLast {
                    sourceDirs.files.map { it.resolve("module-info.java") }.firstOrNull { it.isFile }?.let {
                        it.copyTo(targetDir.get().asFile.resolve("module-info.java"), overwrite = true)
                    }
                }
            }

            tasks.named<Javadoc>("javadoc") {
                setSource(files(delombokDir).builtBy(delombok).asFileTree.matching { include("**/*.java") })
            }
        }
    }
}
